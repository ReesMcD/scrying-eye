import type { Body, MiniSpec } from './spec.js';

/**
 * A figure for every monster in the 2024 rules (SRD 5.2), by name: what it is (a minotaur's bull
 * head, a naga's tail, a griffon's eagle head on a lion), not how it's drawn, so any art style
 * draws them all. Giant animals share their animal's figure; the board draws them bigger.
 * A mini the DM makes on the Minis page always wins over this.
 */

type Extra = Omit<MiniSpec, 'form' | 'body' | 'coat'>;
const beast = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'beast', body, coat, ...extra });
const bird = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'bird', body, coat, ...extra });
const serpent = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'serpent', body, coat, ...extra });
const bug = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'arthropod', body, coat, ...extra });
const sea = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'fish', body, coat, ...extra });
const blob = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'blob', body, coat, ...extra });
const elemental = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'elemental', body, coat, ...extra });
const swarm = (body: Body, coat: string): MiniSpec => ({ form: 'swarm', body, coat });
const plant = (body: Body, coat: string, extra: Extra = {}): MiniSpec => ({ form: 'plant', body, coat, ...extra });
const thing = (body: Body, coat: string): MiniSpec => ({ form: 'object', body, coat });

const glowing = (eyes: string) => ({ eyes, glow: true });
const devil = { tail: 'devil', ears: 'pointed' } as const;

